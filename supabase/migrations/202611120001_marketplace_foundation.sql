begin;

alter table public.products
  add column if not exists attributes jsonb not null default '{}'::jsonb;

create table if not exists public.product_variants (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  sku text,
  attributes jsonb not null default '{}'::jsonb,
  price_bdt integer not null check (price_bdt > 0),
  sale_price_bdt integer check (sale_price_bdt is null or (sale_price_bdt >= 0 and sale_price_bdt <= price_bdt)),
  stock integer not null default 0 check (stock >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists product_variants_sku_unique
  on public.product_variants (sku) where sku is not null and sku <> '';
create index if not exists product_variants_product_id_idx
  on public.product_variants (product_id);

create table if not exists public.seller_wallet_ledger (
  id bigint generated by default as identity primary key,
  commission_id bigint not null unique references public.seller_commissions(id) on delete restrict,
  order_id bigint not null references public.orders(id) on delete restrict,
  seller_id bigint not null references public.users(id) on delete restrict,
  gross_bdt integer not null check (gross_bdt >= 0),
  commission_bdt integer not null check (commission_bdt >= 0),
  earning_bdt integer not null check (earning_bdt >= 0),
  available_after timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists seller_wallet_ledger_seller_created_idx
  on public.seller_wallet_ledger (seller_id, created_at desc);
create index if not exists seller_wallet_ledger_order_idx
  on public.seller_wallet_ledger (order_id);

create or replace function public.capture_seller_commission_ledger()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_hold_days integer := 7;
begin
  select coalesce(nullif(value, '')::integer, 7)
    into v_hold_days
  from public.app_settings
  where key = 'seller_payout_hold_days';

  if v_hold_days is null then v_hold_days := 7; end if;
  if v_hold_days < 0 or v_hold_days > 90 then
    raise exception 'seller_payout_hold_days must be between 0 and 90';
  end if;

  insert into public.seller_wallet_ledger
    (commission_id, order_id, seller_id, gross_bdt, commission_bdt, earning_bdt, available_after)
  values
    (new.id, new.order_id, new.seller_id, new.gross_bdt, new.commission_bdt,
     new.seller_earning_bdt, now() + make_interval(days => v_hold_days))
  on conflict (commission_id) do nothing;

  return new;
end;
$$;

drop trigger if exists seller_commission_ledger_capture on public.seller_commissions;
create trigger seller_commission_ledger_capture
after insert on public.seller_commissions
for each row execute function public.capture_seller_commission_ledger();

-- Read-only balance projection. Earnings are available only after delivery,
-- confirmed payment settlement, and the configured return/hold window.
create or replace view public.seller_wallet_balances
with (security_invoker = true)
as
select
  l.seller_id,
  coalesce(sum(l.earning_bdt) filter (
    where o.status <> 'cancelled'
      and o.status = 'delivered'
      and o.payment_status = 'paid'
      and l.available_after <= now()
  ), 0)::bigint as available_bdt,
  coalesce(sum(l.earning_bdt) filter (
    where o.status <> 'cancelled'
      and not (
        o.status = 'delivered'
        and o.payment_status = 'paid'
        and l.available_after <= now()
      )
  ), 0)::bigint as pending_bdt,
  coalesce(sum(l.gross_bdt), 0)::bigint as lifetime_gross_bdt,
  coalesce(sum(l.commission_bdt), 0)::bigint as lifetime_commission_bdt
from public.seller_wallet_ledger l
join public.orders o on o.id = l.order_id
group by l.seller_id;

alter table public.product_variants enable row level security;
drop policy if exists product_variants_read_visible on public.product_variants;
create policy product_variants_read_visible
on public.product_variants for select to anon, authenticated
using (
  exists (
    select 1 from public.products p
    where p.id = product_variants.product_id
      and (
        p.status = 'approved'
        or (select auth.uid()) is not null and exists (
          select 1 from public.users u
          where u.id = p.seller_id and u.auth_user_id = (select auth.uid())
        )
        or public.is_marketplace_admin()
      )
  )
);

drop policy if exists product_variants_manage_owner_admin on public.product_variants;
create policy product_variants_manage_owner_admin
on public.product_variants for all to authenticated
using (
  exists (
    select 1 from public.products p
    where p.id = product_variants.product_id
      and (
        public.is_marketplace_admin()
        or exists (
          select 1 from public.users u
          where u.id = p.seller_id and u.auth_user_id = (select auth.uid())
        )
      )
  )
)
with check (
  exists (
    select 1 from public.products p
    where p.id = product_variants.product_id
      and (
        public.is_marketplace_admin()
        or exists (
          select 1 from public.users u
          where u.id = p.seller_id and u.auth_user_id = (select auth.uid())
        )
      )
  )
);

alter table public.seller_wallet_ledger enable row level security;
drop policy if exists seller_wallet_ledger_read_owner_admin on public.seller_wallet_ledger;
create policy seller_wallet_ledger_read_owner_admin
on public.seller_wallet_ledger for select to authenticated
using (
  public.is_marketplace_admin()
  or exists (
    select 1 from public.users u
    where u.id = seller_wallet_ledger.seller_id
      and u.auth_user_id = (select auth.uid())
  )
);

grant select on public.seller_wallet_balances to authenticated;
grant select on public.product_variants to anon, authenticated;
grant insert, update, delete on public.product_variants to authenticated;

