-- Daraz affiliate product catalog, isolated from marketplace products and orders.
-- This migration is intentionally review-only until separately approved for production.

CREATE TABLE IF NOT EXISTS public.affiliate_products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  affiliate_platform text NOT NULL DEFAULT 'daraz'
    CHECK (affiliate_platform = 'daraz'),
  product_name text NOT NULL CHECK (length(btrim(product_name)) BETWEEN 1 AND 180),
  category text NOT NULL CHECK (length(btrim(category)) BETWEEN 1 AND 80),
  description text,
  image_url text NOT NULL CHECK (image_url ~ '^https://'),
  product_url text NOT NULL CHECK (product_url ~ '^https://'),
  affiliate_url text NOT NULL CHECK (affiliate_url ~ '^https://'),
  current_price_bdt integer CHECK (current_price_bdt IS NULL OR current_price_bdt >= 0),
  original_price_bdt integer CHECK (original_price_bdt IS NULL OR original_price_bdt >= 0),
  status text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'active', 'paused')),
  is_featured boolean NOT NULL DEFAULT false,
  created_by uuid DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT affiliate_prices_consistent CHECK (
    original_price_bdt IS NULL OR current_price_bdt IS NULL
    OR original_price_bdt >= current_price_bdt
  )
);

ALTER TABLE public.affiliate_products ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON TABLE public.affiliate_products TO anon, authenticated;
GRANT INSERT, UPDATE ON TABLE public.affiliate_products TO authenticated;

DROP POLICY IF EXISTS "Public can view active affiliate products" ON public.affiliate_products;
CREATE POLICY "Public can view active affiliate products"
  ON public.affiliate_products
  FOR SELECT
  TO anon, authenticated
  USING (status = 'active');

DROP POLICY IF EXISTS "OTP verified marketplace admins manage affiliate products" ON public.affiliate_products;
CREATE POLICY "OTP verified marketplace admins manage affiliate products"
  ON public.affiliate_products
  FOR ALL
  TO authenticated
  USING (public.is_marketplace_admin())
  WITH CHECK (public.is_marketplace_admin());


-- One-row-per-platform switch. Disconnect preserves affiliate_products unchanged.
CREATE TABLE IF NOT EXISTS public.affiliate_integrations (
  affiliate_platform text PRIMARY KEY CHECK (affiliate_platform = 'daraz'),
  is_connected boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO public.affiliate_integrations (affiliate_platform, is_connected)
VALUES ('daraz', false)
ON CONFLICT (affiliate_platform) DO NOTHING;

ALTER TABLE public.affiliate_integrations ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON TABLE public.affiliate_integrations TO anon, authenticated;
GRANT INSERT, UPDATE ON TABLE public.affiliate_integrations TO authenticated;

DROP POLICY IF EXISTS "Public can read affiliate integration state" ON public.affiliate_integrations;
CREATE POLICY "Public can read affiliate integration state"
  ON public.affiliate_integrations
  FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "OTP verified marketplace admins manage affiliate integration" ON public.affiliate_integrations;
CREATE POLICY "OTP verified marketplace admins manage affiliate integration"
  ON public.affiliate_integrations
  FOR ALL
  TO authenticated
  USING (public.is_marketplace_admin())
  WITH CHECK (public.is_marketplace_admin());

